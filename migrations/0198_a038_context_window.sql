-- Окно контекста модели на подключении LLM.
--
-- До этого бюджет истории чата был захардкожен в a018 (HISTORY_TOKEN_BUDGET = 120_000),
-- что верно для облачных моделей и неверно для локальных: у Ollama с num_ctx = 32k
-- история просто не влезает, и промпт обрезается на стороне сервера без внятной ошибки.
--
-- Бюджет компакции считается как context_window * 3 / 4, поэтому дефолт 160000 даёт
-- ровно прежние 120000 — поведение существующих подключений не меняется.
ALTER TABLE a038_llm_connection
    ADD COLUMN context_window INTEGER NOT NULL DEFAULT 160000;
