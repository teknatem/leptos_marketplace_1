-- Сброс a034 (отчёт о реализации YM) под переимпорт по кампаниям.
--
-- Идентичность документа a034 сменилась: раньше «кабинет × день», теперь
-- «кабинет × кампания × день» (см. YmRealizationId::stable_for_header). Причина —
-- отчёт о реализации YM помесячный НА КАМПАНИЮ, а импорт тянул только один
-- supplier_id (обычно FBS), из-за чего ybuh не покрывал FBY и сверка выручки
-- (fina p907 vs ybuh a034) давала стабильный односторонний перекос на объём FBY.
--
-- Импорт теперь перебирает все кампании бизнеса и создаёт по документу на каждую
-- модель. Старые документы (со старой идентичностью) и их производные проводки
-- надо снести одноразово, иначе останутся осиротевшие GL/p915 от прежних id.
-- Данные восстановятся полностью при переимпорте отчёта о реализации (u503).

DELETE FROM sys_general_ledger    WHERE registrator_type = 'a034_ym_realization';
DELETE FROM p915_mp_order_events  WHERE registrator_type = 'a034_ym_realization';
DELETE FROM a034_ym_realization;
